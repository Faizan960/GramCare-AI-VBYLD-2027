export function getSummaryMetrics(visitsList = VISITS, alertsList = SEED_ALERTS, patientsList = PATIENTS) {
  const totalPatients = patientsList.length;
  const totalVisits = visitsList.length;
  const activeSurveillanceCases = visitsList.filter((v) => v.is_active_surveillance).length;
  const pendingSync = visitsList.filter((v) => v.sync_status === 'Pending').length;
  const syncedCases = visitsList.filter((v) => v.sync_status === 'Synced').length;
  const activeAlerts = alertsList.filter((a) => a.status !== 'Reviewed').length;
  const reviewedAlerts = alertsList.filter((a) => a.status === 'Reviewed').length;

  return {
    totalPatients,
    totalVisits,
    activeSurveillanceCases,
    pendingSync,
    syncedCases,
    activeAlerts,
    reviewedAlerts,
    monitoredVillages: VILLAGES.length,
  };
}

export function getVillageSummaries(patientsList = PATIENTS, visitsList = VISITS) {
  return VILLAGES.map((v) => {
    const vPatients = patientsList.filter((p) => p.village === v.name).length;
    const vVisits = visitsList.filter((vis) => vis.village === v.name).length;
    const vActive = visitsList.filter((vis) => vis.village === v.name && vis.is_active_surveillance).length;
    return {
      ...v,
      patientCount: vPatients,
      visitCount: vVisits,
      activeCases: vActive,
      cases: vActive, // Canonical active case count for backwards compatibility
    };
  });
}

